-- Kitchen Day phases 3–4: kitchen settings, AI assistant memory, and how
-- each client comment is handled in the kitchen. Purely additive.
-- Rollback:
--   drop table if exists public.kitchen_comment_handling;
--   drop table if exists public.kitchen_ai_memory;
--   drop table if exists public.kitchen_settings;

-- One row per tenant.
create table if not exists public.kitchen_settings (
  tenant_id bigint primary key default 1 references public.tenant(id),
  -- 0 = Sunday … 6 = Saturday. Empty = cook on every delivery day.
  cook_days smallint[] not null default '{}',
  -- Extra % on cook-ahead amounts for days that can still take orders.
  late_order_buffer_pct smallint not null default 0 check (late_order_buffer_pct between 0 and 50),
  updated_at timestamptz not null default now()
);
insert into public.kitchen_settings (tenant_id) values (1) on conflict do nothing;

-- Things the kitchen assistant should remember between conversations.
create table if not exists public.kitchen_ai_memory (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null default 1 references public.tenant(id),
  content text not null check (char_length(content) between 1 and 500),
  active boolean not null default true,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);

-- How a client's comment affects one subrecipe of the dish it was left on:
-- assembly = leave something out / add when assembling the portion;
-- separate_pot = cook this client's servings apart; ignore = doesn't concern
-- this subrecipe. Keyed on the comment text, so an edited comment is
-- sorted again.
create table if not exists public.kitchen_comment_handling (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null default 1 references public.tenant(id),
  user_id uuid not null,
  recipe_id bigint references public.recipe(id) on delete cascade,
  subrecipe_id bigint not null references public.subrecipe(id) on delete cascade,
  comment text not null,
  handling text not null check (handling in ('assembly', 'separate_pot', 'ignore')),
  instruction text,
  decided_by text not null default 'admin' check (decided_by in ('ai', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists kitchen_comment_handling_key
  on public.kitchen_comment_handling (user_id, coalesce(recipe_id, 0), subrecipe_id, comment);

alter table public.kitchen_settings enable row level security;
alter table public.kitchen_ai_memory enable row level security;
alter table public.kitchen_comment_handling enable row level security;

create policy kitchen_settings_admin on public.kitchen_settings
  for all to authenticated using (is_admin()) with check (is_admin());
create policy kitchen_ai_memory_admin on public.kitchen_ai_memory
  for all to authenticated using (is_admin()) with check (is_admin());
create policy kitchen_comment_handling_admin on public.kitchen_comment_handling
  for all to authenticated using (is_admin()) with check (is_admin());
