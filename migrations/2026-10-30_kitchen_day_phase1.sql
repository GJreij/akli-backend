-- Kitchen Day, phase 1: cooked-batch stock + shelf life / equipment metadata.
-- Purely additive: no existing column changes, no data rewritten.
-- Rollback: 2026-10-30_kitchen_day_phase1_rollback.sql

-- ---------------------------------------------------------------
-- Subrecipe: how it's made and how long it keeps once made
-- ---------------------------------------------------------------
alter table public.subrecipe
  -- cook = heat involved; assemble = cut/mix/dress, no heat;
  -- ready = bought/portion-only (honey, nuts, yogurt, bread)
  add column if not exists prep_type text not null default 'cook'
    check (prep_type in ('cook', 'assemble', 'ready')),
  -- days a cooked batch keeps in the fridge (null = unknown → same-day only)
  add column if not exists fridge_days smallint check (fridge_days >= 0),
  -- days it keeps frozen; null = don't freeze. Kept alongside the existing
  -- `freezable` flag, which the catalog UI still writes.
  add column if not exists freezer_days smallint check (freezer_days >= 0),
  -- main piece of equipment it ties up (5 stove burners + 1 home oven today)
  add column if not exists equipment text
    check (equipment in ('stove', 'oven', 'grill', 'none')),
  add column if not exists active_minutes smallint check (active_minutes >= 0),
  add column if not exists total_minutes smallint check (total_minutes >= 0),
  -- who can do it: chef, or a helper doing light jobs
  add column if not exists skill text not null default 'chef'
    check (skill in ('chef', 'helper'));

-- ---------------------------------------------------------------
-- Ingredient: just enough for the shopping list + thaw reminders.
-- No pantry quantities on purpose.
-- ---------------------------------------------------------------
alter table public.ingredient
  -- always in the kitchen (oil, salt, spices) → left off shopping lists
  add column if not exists is_staple boolean not null default false,
  -- bought/kept frozen (chicken, minced meat) → thaw reminder the day before
  add column if not exists stored_frozen boolean not null default false,
  add column if not exists thaw_hours smallint check (thaw_hours >= 0);

-- ---------------------------------------------------------------
-- Cooked batches: one row per pot/tray actually cooked.
-- "Already cooked" for a subrecipe = servings_cooked of active batches
-- minus servings linked to them (meal_plan_day_recipe_serving.batch_id)
-- minus discarded_servings.
-- ---------------------------------------------------------------
create table if not exists public.kitchen_batch (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null default 1 references public.tenant(id),
  subrecipe_id bigint not null references public.subrecipe(id),
  cooked_on date not null default current_date,
  servings_cooked real not null check (servings_cooked > 0),
  cooked_weight_g real check (cooked_weight_g > 0),
  storage text not null default 'fridge' check (storage in ('fridge', 'freezer')),
  use_by date,
  -- set for a separate pot made for a client comment ("no garlic")
  variant_note text,
  status text not null default 'active' check (status in ('active', 'finished', 'discarded')),
  discarded_servings real not null default 0 check (discarded_servings >= 0),
  notes text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists kitchen_batch_sub_status_idx
  on public.kitchen_batch (subrecipe_id, status);

alter table public.meal_plan_day_recipe_serving
  add column if not exists batch_id bigint references public.kitchen_batch(id) on delete set null;

create index if not exists mpdrs_batch_id_idx
  on public.meal_plan_day_recipe_serving (batch_id) where batch_id is not null;

alter table public.kitchen_batch enable row level security;

create policy kitchen_batch_select_admin on public.kitchen_batch
  for select to authenticated using (is_admin());
create policy kitchen_batch_insert_admin on public.kitchen_batch
  for insert to authenticated with check (is_admin());
create policy kitchen_batch_update_admin on public.kitchen_batch
  for update to authenticated using (is_admin()) with check (is_admin());
create policy kitchen_batch_delete_admin on public.kitchen_batch
  for delete to authenticated using (is_admin());
